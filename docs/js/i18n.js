/** t("lab.share", {p: 30}) looks the key up in the current language, falling back to English. */
export function t(key, vars) {
  const find = dict => key.split(".").reduce((o, k) => (o == null ? o : o[k]), dict);
  const v = find(STR[lang]) ?? find(en);
  return typeof v === "function" ? v(vars || {}) : v;
}
